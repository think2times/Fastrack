WITH LATEST_PRICE AS (
    -- 提前查出当前最新的价格信息，只计算一次
    SELECT PRICE_CODE, PRICE_NAME
    FROM CSM.PRICE_INFO
    WHERE PRICE_LIST_ID = (SELECT MAX(PRICE_LIST_ID) FROM CSM.PRICE_INFO)
)
SELECT 
    MC.CARD_ID,
    MC.CARD_NAME,
    MC.CARD_NAME_PY,
    MC.CARD_ADDRESS,
    MC.CARD_ADDRESS_PY,
    P.SUBCOM_NAME,
    R.REGION_NAME AS REGION_ID,
    MC.INSTALL_POSITION,
    MC.CONTRACT_NO,
    TO_CHAR(MC.SIGN_DATE, 'yyyy-mm-dd') AS SIGN_DATE,
    CASE WHEN MC.PAY_METHOD = 1 THEN '现金' ELSE '其他' END AS PAY_METHOD,
    LP.PRICE_NAME AS PRICE_CODE,
    MC.PERSON_COUNT,
    NVL(MC.FAMILY_COUNT, 1) AS FAMILY_COUNT,
    MC.DISABLE_DATE,
    TO_CHAR(MC.DEREGISTER_DATE, 'yyyy-mm-dd') AS DEREGISTER_DATE,
    WORD.WORD_TEXT AS CARD_INDUSTRY,
    CASE WHEN MC.METERCARD_STATE = 0 THEN '正常' ELSE '异常' END AS METERCARD_STATE,
    CU1.USER_NAME AS CREATOR_ID,
    TO_CHAR(MC.CREATE_DATE, 'yyyy-mm-dd') AS CREATE_DATE,
    CU2.USER_NAME AS MODIFIER_ID,
    TO_CHAR(MC.LAST_MODIFY_DATE, 'yyyy-mm-dd') AS LAST_MODIFY_DATE,
    MC.MAIN_METERCARD_ID,
    CASE WHEN MC.METERCARD_TYPE = 1 THEN '普通卡' 
         WHEN MC.METERCARD_TYPE = 2 THEN '副卡' 
         ELSE '主卡' END AS METERCARD_TYPE,
    CASE WHEN MC.BILL_TYPE = 1 THEN '开账在副卡' ELSE '开账在主卡' END AS BILL_TYPE,
    MC.PAYER_CARD_ID,
    MC.STANDARD_ADDRESS,
    CASE WHEN MC.IS_BINDING_WECHAT = 0 THEN '未绑定' ELSE '已绑定' END AS IS_BINDING_WECHAT,
    CASE WHEN MC.USER_TYPE = 0 THEN '居民户' ELSE '非居民户' END AS USER_TYPE,
    MC.CONTACT_CELLPHONE,
    MC.CONTACT_TELPHONE,
    C.CERTIFICATE_CODE
FROM CSM.CM_METERCARDS MC
LEFT JOIN CSM.CSM_SUBCOMPANIES P ON MC.SUBCOM_CODE = P.SUBCOM_CODE
LEFT JOIN CSM.CSM_REGIONS R ON MC.REGION_ID = R.REGION_ID
LEFT JOIN LATEST_PRICE LP ON MC.PRICE_CODE = LP.PRICE_CODE
-- 优化字典表的关联方式，直接在 ON 中过滤 GROUP_KEY
LEFT JOIN CSM.CSM_WORDS WORD ON MC.CARD_INDUSTRY = WORD.WORD_VALUE AND WORD.WORD_GROUP_KEY = 'CARD_INDUSTRY'
LEFT JOIN CSM.CM_CUSTOMERS C ON MC.CUSTOMER_ID = C.CUSTOMER_ID
LEFT JOIN CSM.CSM_USERS CU1 ON C.CREATOR_ID = CU1.USER_ID
LEFT JOIN CSM.CSM_USERS CU2 ON C.MODIFIER_ID = CU2.USER_ID
WHERE MC.SUBCOM_CODE IN ('011', '021', '031', '032', '041', '051', '061', '062')
      AND MC.LAST_MODIFY_DATE >= SYSDATE-1
      AND MC.LAST_MODIFY_DATE < SYSDATE